import { HttpClient, HttpParams } from '@angular/common/http';
import { inject, Injectable } from '@angular/core';
import { Observable } from 'rxjs';

import { environment } from '../../../../../../environments/environment';

import {
  CreateWarehouseRequest,
  UpdateWarehouseRequest,
  Warehouse,
  WarehouseListQuery,
  WarehousePagedResult
} from '../models/warehouse.model';

@Injectable({
  providedIn: 'root'
})
export class WarehouseService {

  // =========================================================
  // Dependencies
  // =========================================================

  private readonly http = inject(HttpClient);

  // =========================================================
  // API Configuration
  // =========================================================

  private readonly apiUrl =
    `${environment.apiBaseUrl}/branches`;

  // =========================================================
  // Get Warehouses
  //
  // GET /api/branches/{branchId}/warehouses
  //
  // Features:
  // - Branch-scoped directory
  // - Code and name filtering
  // - Warehouse type filtering
  // - Active / inactive filtering
  // - Server-side sorting
  // - Server-side pagination
  //
  // Authorization is enforced by the backend.
  // =========================================================

  getWarehouses(
    branchId: number,
    query: WarehouseListQuery = {}
  ): Observable<WarehousePagedResult> {

    let params = new HttpParams();

    if (query.code !== undefined && query.code.trim() !== '') {
      params = params.set('code', query.code.trim());
    }

    if (query.name !== undefined && query.name.trim() !== '') {
      params = params.set('name', query.name.trim());
    }

    if (query.type !== undefined) {
      params = params.set('type', String(query.type));
    }

    if (query.isActive !== undefined) {
      params = params.set('isActive', String(query.isActive));
    }

    if (query.includeInactive !== undefined) {
      params = params.set(
        'includeInactive',
        String(query.includeInactive)
      );
    }

    if (query.sortBy !== undefined) {
      params = params.set('sortBy', query.sortBy);
    }

    if (query.sortDirection !== undefined) {
      params = params.set(
        'sortDirection',
        query.sortDirection
      );
    }

    if (query.pageNumber !== undefined) {
      params = params.set(
        'pageNumber',
        String(query.pageNumber)
      );
    }

    if (query.pageSize !== undefined) {
      params = params.set(
        'pageSize',
        String(query.pageSize)
      );
    }

    return this.http.get<WarehousePagedResult>(
      `${this.apiUrl}/${branchId}/warehouses`,
      { params }
    );
  }

  // =========================================================
  // Get Warehouse By ID
  //
  // GET /api/branches/{branchId}/warehouses/{warehouseId}
  //
  // Features:
  // - Retrieve a single warehouse
  // - Branch-scoped lookup
  // - Retrieve RowVersion for optimistic concurrency
  //
  // Authorization is enforced by the backend.
  // =========================================================

  getWarehouseById(
    branchId: number,
    warehouseId: number
  ): Observable<Warehouse> {

    return this.http.get<Warehouse>(
      `${this.apiUrl}/${branchId}/warehouses/${warehouseId}`
    );
  }

  // =========================================================
  // Create Warehouse
  //
  // POST /api/branches/{branchId}/warehouses
  //
  // Requires SuperAdmin authorization.
  //
  // Warehouse code is generated by the backend.
  //
  // Business Rules:
  //
  // 1. The first warehouse automatically becomes default.
  //
  // 2. A later warehouse may be created as default.
  //
  // 3. AllowSales is independent of IsDefault.
  //
  // 4. Warehouse code is unique within its branch.
  // =========================================================

  createWarehouse(
    branchId: number,
    request: CreateWarehouseRequest
  ): Observable<Warehouse> {

    return this.http.post<Warehouse>(
      `${this.apiUrl}/${branchId}/warehouses`,
      request
    );
  }

  // =========================================================
  // Update Warehouse
  //
  // PUT /api/branches/{branchId}/warehouses/{warehouseId}
  //
  // Requires SuperAdmin authorization.
  //
  // Editable properties:
  // - Name
  // - Type
  // - AllowSales
  //
  // Protected properties:
  // - Code
  // - IsDefault
  // - IsActive
  //
  // Uses RowVersion for optimistic concurrency.
  //
  // HTTP Responses:
  // - 200: Updated Warehouse
  // - 400: Validation failed
  // - 401/403: Unauthorized / Forbidden
  // - 404: Warehouse not found
  // - 409: Concurrency or dependency conflict
  //
  // Error handling is performed by the component.
  // =========================================================

  updateWarehouse(
    branchId: number,
    warehouseId: number,
    request: UpdateWarehouseRequest
  ): Observable<Warehouse> {

    return this.http.put<Warehouse>(
      `${this.apiUrl}/${branchId}/warehouses/${warehouseId}`,
      request
    );
  }
}