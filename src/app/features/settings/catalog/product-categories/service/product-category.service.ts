
import { HttpClient, HttpParams } from '@angular/common/http';
import { inject, Injectable } from '@angular/core';
import { Observable } from 'rxjs';

import { environment } from '../../../../../../environments/environment';

import {
  ChangeProductCategoryStatusRequest,
  CreateProductCategoryRequest,
  ProductCategory,
  ProductCategoryListQuery,
  ProductCategoryPagedResult,
  UpdateProductCategoryRequest
} from '../models/product-category.model';

@Injectable({
  providedIn: 'root'
})
export class ProductCategoryService {

  // =========================================================
  // Dependencies
  // =========================================================

  private readonly http = inject(HttpClient);

  // =========================================================
  // API Configuration
  // =========================================================

  private readonly apiUrl =
    `${environment.apiBaseUrl}/companies`;

  // =========================================================
  // Get Product Categories
  //
  // GET /api/companies/{companyId}/product-categories
  //
  // Required permission:
  // - product.category.view
  //
  // Authorization is enforced by the backend.
  // =========================================================

  getProductCategories(
    companyId: number,
    query: ProductCategoryListQuery = {}
  ): Observable<ProductCategoryPagedResult> {

    let params = new HttpParams();

    if (query.code !== undefined && query.code.trim() !== '') {
      params = params.set('code', query.code.trim());
    }

    if (query.name !== undefined && query.name.trim() !== '') {
      params = params.set('name', query.name.trim());
    }

    if (query.parentCategoryId !== undefined) {
      params = params.set(
        'parentCategoryId',
        String(query.parentCategoryId)
      );
    }

    if (query.isActive !== undefined) {
      params = params.set(
        'isActive',
        String(query.isActive)
      );
    }

    if (query.includeInactive !== undefined) {
      params = params.set(
        'includeInactive',
        String(query.includeInactive)
      );
    }

    if (query.sortBy !== undefined) {
      params = params.set('sortBy', query.sortBy);
    }

    if (query.sortDirection !== undefined) {
      params = params.set(
        'sortDirection',
        query.sortDirection
      );
    }

    if (query.pageNumber !== undefined) {
      params = params.set(
        'pageNumber',
        String(query.pageNumber)
      );
    }

    if (query.pageSize !== undefined) {
      params = params.set(
        'pageSize',
        String(query.pageSize)
      );
    }

    return this.http.get<ProductCategoryPagedResult>(
      `${this.apiUrl}/${companyId}/product-categories`,
      { params }
    );
  }

  // =========================================================
  // Get Product Category By ID
  //
  // GET /api/companies/{companyId}/product-categories/{id}
  //
  // Required permission:
  // - product.category.view
  // =========================================================

  getProductCategoryById(
    companyId: number,
    categoryId: number
  ): Observable<ProductCategory> {

    return this.http.get<ProductCategory>(
      `${this.apiUrl}/${companyId}/product-categories/${categoryId}`
    );
  }

  // =========================================================
  // Create Product Category
  //
  // POST /api/companies/{companyId}/product-categories
  //
  // Required permission:
  // - product.category.create
  //
  // Category code is generated by the backend.
  // =========================================================

  createProductCategory(
    companyId: number,
    request: CreateProductCategoryRequest
  ): Observable<ProductCategory> {

    return this.http.post<ProductCategory>(
      `${this.apiUrl}/${companyId}/product-categories`,
      request
    );
  }

  // =========================================================
  // Update Product Category
  //
  // PUT /api/companies/{companyId}/product-categories/{id}
  //
  // Required permission:
  // - product.category.update
  //
  // Editable properties:
  // - Name
  // - ParentCategoryId
  //
  // Uses RowVersion for optimistic concurrency.
  // =========================================================

  updateProductCategory(
    companyId: number,
    categoryId: number,
    request: UpdateProductCategoryRequest
  ): Observable<ProductCategory> {

    return this.http.put<ProductCategory>(
      `${this.apiUrl}/${companyId}/product-categories/${categoryId}`,
      request
    );
  }

  // =========================================================
  // Activate Product Category
  //
  // PUT /api/companies/{companyId}/product-categories/{id}/activate
  //
  // Required permission:
  // - product.category.activate
  // =========================================================

  activateProductCategory(
    companyId: number,
    categoryId: number,
    request: ChangeProductCategoryStatusRequest
  ): Observable<ProductCategory> {

    return this.http.put<ProductCategory>(
      `${this.apiUrl}/${companyId}/product-categories/${categoryId}/activate`,
      request
    );
  }

  // =========================================================
  // Deactivate Product Category
  //
  // PUT /api/companies/{companyId}/product-categories/{id}/deactivate
  //
  // Required permission:
  // - product.category.deactivate
  // =========================================================

  deactivateProductCategory(
    companyId: number,
    categoryId: number,
    request: ChangeProductCategoryStatusRequest
  ): Observable<ProductCategory> {

    return this.http.put<ProductCategory>(
      `${this.apiUrl}/${companyId}/product-categories/${categoryId}/deactivate`,
      request
    );
  }
}