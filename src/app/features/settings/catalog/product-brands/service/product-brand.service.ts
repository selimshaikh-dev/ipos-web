import { HttpClient, HttpParams } from '@angular/common/http';
import { inject, Injectable } from '@angular/core';
import { Observable } from 'rxjs';

import { environment } from '../../../../../../environments/environment';

import {
  ChangeProductBrandStatusRequest,
  CreateProductBrandRequest,
  ProductBrand,
  ProductBrandListQuery,
  ProductBrandPagedResult,
  UpdateProductBrandRequest
} from '../models/product-brand.model';

@Injectable({
  providedIn: 'root'
})
export class ProductBrandService {

  // =========================================================
  // Dependencies
  // =========================================================

  private readonly http = inject(HttpClient);

  // =========================================================
  // API Configuration
  // =========================================================

  private readonly apiUrl =
    `${environment.apiBaseUrl}/companies`;

  // =========================================================
  // Get Product Brands
  //
  // GET /api/companies/{companyId}/product-brands
  //
  // Required permission:
  // - product.brand.view
  //
  // Authorization is enforced by the backend.
  // =========================================================

  getProductBrands(
    companyId: number,
    query: ProductBrandListQuery = {}
  ): Observable<ProductBrandPagedResult> {

    let params = new HttpParams();

    if (query.code !== undefined && query.code.trim() !== '') {
      params = params.set('code', query.code.trim());
    }

    if (query.name !== undefined && query.name.trim() !== '') {
      params = params.set('name', query.name.trim());
    }

    if (query.isActive !== undefined) {
      params = params.set(
        'isActive',
        String(query.isActive)
      );
    }

    if (query.includeInactive !== undefined) {
      params = params.set(
        'includeInactive',
        String(query.includeInactive)
      );
    }

    if (query.sortBy !== undefined) {
      params = params.set('sortBy', query.sortBy);
    }

    if (query.sortDirection !== undefined) {
      params = params.set(
        'sortDirection',
        query.sortDirection
      );
    }

    if (query.pageNumber !== undefined) {
      params = params.set(
        'pageNumber',
        String(query.pageNumber)
      );
    }

    if (query.pageSize !== undefined) {
      params = params.set(
        'pageSize',
        String(query.pageSize)
      );
    }

    return this.http.get<ProductBrandPagedResult>(
      `${this.apiUrl}/${companyId}/product-brands`,
      { params }
    );
  }

  // =========================================================
  // Get Product Brand By ID
  //
  // GET /api/companies/{companyId}/product-brands/{brandId}
  //
  // Required permission:
  // - product.brand.view
  // =========================================================

  getProductBrandById(
    companyId: number,
    brandId: number
  ): Observable<ProductBrand> {

    return this.http.get<ProductBrand>(
      `${this.apiUrl}/${companyId}/product-brands/${brandId}`
    );
  }

  // =========================================================
  // Create Product Brand
  //
  // POST /api/companies/{companyId}/product-brands
  //
  // Required permission:
  // - product.brand.create
  //
  // Brand code is generated by the backend.
  // =========================================================

  createProductBrand(
    companyId: number,
    request: CreateProductBrandRequest
  ): Observable<ProductBrand> {

    return this.http.post<ProductBrand>(
      `${this.apiUrl}/${companyId}/product-brands`,
      request
    );
  }

  // =========================================================
  // Update Product Brand
  //
  // PUT /api/companies/{companyId}/product-brands/{brandId}
  //
  // Required permission:
  // - product.brand.update
  //
  // Editable properties:
  // - Name
  //
  // Uses RowVersion for optimistic concurrency.
  // =========================================================

  updateProductBrand(
    companyId: number,
    brandId: number,
    request: UpdateProductBrandRequest
  ): Observable<ProductBrand> {

    return this.http.put<ProductBrand>(
      `${this.apiUrl}/${companyId}/product-brands/${brandId}`,
      request
    );
  }

  activateProductBrand(
    companyId: number, brandId: number, request: ChangeProductBrandStatusRequest
  ): Observable<ProductBrand> {
    return this.http.put<ProductBrand>(
      `${this.apiUrl}/${companyId}/product-brands/${brandId}/activate`, request
    );
  }

  deactivateProductBrand(
    companyId: number, brandId: number, request: ChangeProductBrandStatusRequest
  ): Observable<ProductBrand> {
    return this.http.put<ProductBrand>(
      `${this.apiUrl}/${companyId}/product-brands/${brandId}/deactivate`, request
    );
  }

}